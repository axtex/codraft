import { NextRequest, NextResponse } from 'next/server'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'
import { auth } from '@/auth'
import { prisma } from '@/lib/prisma'

function slugify(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'codraft-export'
  )
}

function formatDate(d: Date): string {
  return d.toLocaleString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  })
}

/** Standard PDF fonts are WinAnsi — fold common punctuation so save() doesn't throw. */
function toWinAnsi(text: string): string {
  return text.replace(/[^\t\n\r\x20-\x7E]/g, (ch) => {
    const folded: Record<string, string> = {
      '\u2018': "'",
      '\u2019': "'",
      '\u201C': '"',
      '\u201D': '"',
      '\u2013': '-',
      '\u2014': '-',
      '\u2026': '...',
      '\u00A0': ' ',
      '\u00B7': '-',
    }
    return folded[ch] ?? '?'
  })
}

function wrapLines(
  text: string,
  font: { widthOfTextAtSize: (t: string, size: number) => number },
  size: number,
  maxWidth: number
): string[] {
  const lines: string[] = []
  for (const paragraph of text.split('\n')) {
    const words = paragraph.split(/\s+/).filter(Boolean)
    if (words.length === 0) {
      lines.push('')
      continue
    }
    let current = ''
    for (const word of words) {
      if (font.widthOfTextAtSize(word, size) > maxWidth) {
        if (current) {
          lines.push(current)
          current = ''
        }
        let chunk = ''
        for (const ch of word) {
          const nextChunk = chunk + ch
          if (font.widthOfTextAtSize(nextChunk, size) <= maxWidth) {
            chunk = nextChunk
          } else {
            if (chunk) lines.push(chunk)
            chunk = ch
          }
        }
        current = chunk
        continue
      }
      const next = current ? `${current} ${word}` : word
      if (font.widthOfTextAtSize(next, size) <= maxWidth) {
        current = next
      } else {
        if (current) lines.push(current)
        current = word
      }
    }
    if (current) lines.push(current)
  }
  return lines
}

async function buildPdf(roomName: string, dateStr: string, sections: { name: string; content: string | null }[]) {
  const doc = await PDFDocument.create()
  const bodyFont = await doc.embedFont(StandardFonts.TimesRoman)
  const boldFont = await doc.embedFont(StandardFonts.TimesRomanBold)

  const pageWidth = 612
  const pageHeight = 792
  const margin = 54
  const maxWidth = pageWidth - margin * 2
  const ink = rgb(0.07, 0.07, 0.09)

  let page = doc.addPage([pageWidth, pageHeight])
  let y = pageHeight - margin

  function ensureSpace(needed: number) {
    if (y - needed < margin) {
      page = doc.addPage([pageWidth, pageHeight])
      y = pageHeight - margin
    }
  }

  function drawWrapped(text: string, size: number, font: typeof bodyFont, leading: number) {
    const lines = wrapLines(toWinAnsi(text), font, size, maxWidth)
    for (const line of lines) {
      ensureSpace(leading)
      if (line) {
        page.drawText(line, { x: margin, y: y - size, size, font, color: ink })
      }
      y -= leading
    }
  }

  drawWrapped(roomName, 22, boldFont, 28)
  y -= 6
  drawWrapped(`Generated by codraft · ${dateStr}`, 10, bodyFont, 14)
  y -= 16

  for (const section of sections) {
    ensureSpace(36)
    drawWrapped(section.name, 14, boldFont, 20)
    y -= 4
    const body = section.content?.trim() ? section.content : 'This section is empty.'
    drawWrapped(body, 11, bodyFont, 16)
    y -= 18
  }

  return doc.save()
}

export async function GET(
  req: NextRequest,
  { params }: { params: { id: string } }
) {
  const session = await auth()
  if (!session?.user?.id) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  const member = await prisma.roomMember.findUnique({
    where: { roomId_userId: { roomId: params.id, userId: session.user.id } },
  })
  if (!member) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 403 })
  }

  const format = req.nextUrl.searchParams.get('format') ?? 'markdown'
  if (format !== 'markdown' && format !== 'pdf') {
    return NextResponse.json({ error: 'format must be markdown or pdf' }, { status: 400 })
  }

  const room = await prisma.room.findUnique({
    where: { id: params.id },
    include: {
      sections: { orderBy: { order: 'asc' } },
    },
  })
  if (!room) {
    return NextResponse.json({ error: 'Room not found' }, { status: 404 })
  }

  const now = new Date()
  const dateStr = formatDate(now)

  if (format === 'markdown') {
    const body = [
      `# ${room.name}`,
      `> Generated by codraft · ${dateStr}`,
      '',
      '---',
      '',
      ...room.sections.flatMap((s) => [
        `## ${s.name}`,
        s.content?.trim() ? s.content : '_This section is empty._',
        '',
        '---',
        '',
      ]),
    ].join('\n')

    return new NextResponse(body, {
      headers: {
        'Content-Type': 'text/markdown; charset=utf-8',
        'Content-Disposition': `attachment; filename="${slugify(room.name)}.md"`,
      },
    })
  }

  const bytes = await buildPdf(
    room.name,
    dateStr,
    room.sections.map((s) => ({ name: s.name, content: s.content }))
  )

  return new NextResponse(Buffer.from(bytes), {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="${slugify(room.name)}.pdf"`,
    },
  })
}
