import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { getRequest } from './request'

const session = { user: { id: 'user-1', username: 'ada', name: 'Ada' } }

const { auth, prisma } = vi.hoisted(() => ({
  auth: vi.fn(),
  prisma: {
    roomMember: { findUnique: vi.fn() },
    room: { findUnique: vi.fn() },
  },
}))

vi.mock('@/auth', () => ({ auth }))
vi.mock('@/lib/prisma', () => ({ prisma }))

import { GET } from '@/app/api/rooms/[id]/export/route'

const params = { id: 'room-1' }

function exportRoom(format?: string) {
  const query = format ? `?format=${format}` : ''
  return GET(getRequest(`http://localhost:3000/api/rooms/room-1/export${query}`), { params })
}

beforeEach(() => {
  auth.mockReset()
  auth.mockResolvedValue(session)
  prisma.roomMember.findUnique.mockReset()
  prisma.roomMember.findUnique.mockResolvedValue({ role: 'EDITOR', userId: 'user-1' })
  prisma.room.findUnique.mockReset()
})

afterEach(() => {
  vi.useRealTimers()
})

describe('GET /api/rooms/:id/export', () => {
  it('rejects a signed-out caller with 401', async () => {
    auth.mockResolvedValue(null)

    const res = await exportRoom('markdown')

    expect(res.status).toBe(401)
    expect(await res.json()).toEqual({ error: 'Unauthorized' })
    expect(prisma.roomMember.findUnique).not.toHaveBeenCalled()
  })

  it('rejects an unknown format', async () => {
    const res = await exportRoom('docx')

    expect(res.status).toBe(400)
    expect(await res.json()).toEqual({ error: 'format must be markdown or pdf' })
    expect(prisma.room.findUnique).not.toHaveBeenCalled()
  })

  it('renders markdown with section bodies and an empty placeholder', async () => {
    const when = new Date('2026-04-02T15:04:00Z')
    vi.useFakeTimers({ toFake: ['Date'] })
    vi.setSystemTime(when)
    const dateStr = when.toLocaleString('en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: 'numeric',
      minute: '2-digit',
    })

    prisma.room.findUnique.mockResolvedValue({
      id: 'room-1',
      name: 'Weekend in Porto',
      sections: [
        { name: 'Hotels', content: 'The riverside inn', order: 0 },
        { name: 'Budget', content: '   ', order: 1 },
        { name: 'Notes', content: null, order: 2 },
      ],
    })

    const res = await exportRoom('markdown')
    const body = await res.text()

    expect(res.status).toBe(200)
    expect(res.headers.get('content-type')).toBe('text/markdown; charset=utf-8')
    expect(res.headers.get('content-disposition')).toBe('attachment; filename="weekend-in-porto.md"')
    expect(prisma.room.findUnique).toHaveBeenCalledWith({
      where: { id: 'room-1' },
      include: { sections: { orderBy: { order: 'asc' } } },
    })
    expect(body).toBe(
      [
        '# Weekend in Porto',
        `> Generated by codraft · ${dateStr}`,
        '',
        '---',
        '',
        '## Hotels',
        'The riverside inn',
        '',
        '---',
        '',
        '## Budget',
        '_This section is empty._',
        '',
        '---',
        '',
        '## Notes',
        '_This section is empty._',
        '',
        '---',
        '',
      ].join('\n')
    )
  })
})
